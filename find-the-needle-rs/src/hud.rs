pub fn char_index(c: char) -> Option<u16> {
    let cu = c.to_ascii_uppercase();
    FONT.iter().position(|(fc, _)| *fc == cu).map(|i| i as u16)
}

/// Builds a 128x64 R8 atlas: 16 columns x 8 rows of 8x8 cells (5x7 glyphs).
pub fn build_atlas() -> Vec<u8> {
    let mut tex = vec![0u8; 128 * 64];
    for (ci, (_, rows)) in FONT.iter().enumerate() {
        let cell_x = (ci % 16) * 8;
        let cell_y = (ci / 16) * 8;
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..5 {
                if bits & (1 << (4 - rx)) != 0 {
                    let x = cell_x + rx;
                    let y = cell_y + ry;
                    tex[y * 128 + x] = 255;
                }
            }
        }
    }
    tex
}

/// UV rect for a char in the atlas (normalized).
pub fn char_uv(c: char) -> Option<[f32; 4]> {
    let idx = char_index(c)?;
    let cx = (idx % 16) as f32 * 8.0;
    let cy = (idx / 16) as f32 * 8.0;
    Some([cx / 128.0, cy / 64.0, 5.0 / 128.0, 7.0 / 64.0])
}

/// One HUD quad instance: 48 bytes.
/// a = (x, y, w, h) pixels. b = (u0, v0, u1, v1). c = (r, g, b, a).
/// a == 0.999 -> ring mode, a == 0.998 -> hexagon mode, else glyph/rect via uv.
#[repr(C)]
#[derive(Clone, Copy, bytemuck::Pod, bytemuck::Zeroable)]
pub struct HudQuad {
    pub a: [f32; 4],
    pub b: [f32; 4],
    pub c: [f32; 4],
}

pub struct Hud {
    pub quads: Vec<HudQuad>,
}

impl Hud {
    pub fn new() -> Self {
        Hud { quads: Vec::with_capacity(1024) }
    }

    pub fn clear(&mut self) {
        self.quads.clear();
    }

    pub fn rect(&mut self, x: f32, y: f32, w: f32, h: f32, c: [f32; 4]) {
        self.quads.push(HudQuad {
            a: [x, y, w, h],
            b: [0.0, 0.0, 0.0, 0.0], // zero uv = solid
            c,
        });
    }

    pub fn ring(&mut self, cx: f32, cy: f32, r: f32, thickness: f32, color: [f32; 3]) {
        self.quads.push(HudQuad {
            a: [cx - r - thickness, cy - r - thickness, (r + thickness) * 2.0, (r + thickness) * 2.0],
            b: [r, thickness, 0.0, 0.0],
            c: [color[0], color[1], color[2], 0.999],
        });
    }

    pub fn hex(&mut self, cx: f32, cy: f32, r: f32, color: [f32; 3]) {
        self.quads.push(HudQuad {
            a: [cx - r, cy - r, r * 2.0, r * 2.0],
            b: [r, 0.30, 0.0, 0.0], // b[1] = border thickness ratio
            c: [color[0], color[1], color[2], 0.998],
        });
    }

    /// Draw text, returns pixel width. scale = pixel size of one glyph row.
    pub fn text(&mut self, x: f32, y: f32, scale: f32, color: [f32; 4], s: &str) -> f32 {
        let mut cx = x;
        for ch in s.chars() {
            if ch == ' ' {
                cx += 6.0 * scale;
                continue;
            }
            if let Some(uv) = char_uv(ch) {
                self.quads.push(HudQuad {
                    a: [cx, y, 5.0 * scale, 7.0 * scale],
                    b: uv,
                    c: color,
                });
            }
            cx += 6.0 * scale;
        }
        cx - x
    }

    pub fn text_w(s: &str, scale: f32) -> f32 {
        s.chars().count() as f32 * 6.0 * scale
    }

    /// Centered text.
    pub fn text_center(&mut self, cx: f32, y: f32, scale: f32, color: [f32; 4], s: &str) {
        let w = Self::text_w(s, scale);
        self.text(cx - w / 2.0, y, scale, color, s);
    }
}
